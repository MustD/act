/** One line of the licence list: `Name version — Licence, Licence`. */
internal data class LicenceLine(val text: String)

/**
 * The open-source libraries this build ships, from `files/aboutlibraries.json` (regenerated by
 * `mise run licences`). Null when the resource cannot be read or parsed, which the list reports as such
 * rather than showing nothing, which would look like "no dependencies".
 */
internal suspend fun loadLicences(): List<LicenceLine>? = runCatching {
    Libs.Builder().withJson(Res.readBytes("files/aboutlibraries.json").decodeToString()).build()
        .libraries
        .sortedBy { it.name.lowercase() }
        .map { lib ->
            val licences = lib.licenses.joinToString(", ") { it.name }
            LicenceLine(
                buildString {
                    append(lib.name)
                    lib.artifactVersion?.let { append(' ').append(it) }
                    if (licences.isNotEmpty()) append(" — ").append(licences)
                },
            )
        }
}.getOrNull()

/**
 * The `// licences` body: collapsed to one link, because the list is a couple of hundred lines on a Screen
 * that is mostly about something else, and a plain column (not a lazy one) because the Screen scrolls.
 */
@Composable
internal fun LicenceList() {
    var expanded by rememberSaveable { mutableStateOf(false) }
    val lines by produceState<List<LicenceLine>?>(null, expanded) {
        if (expanded && value == null) value = loadLicences() ?: emptyList()
    }
    Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
        Text(
            "Built with open-source software.",
            style = Act.type.meta,
            color = Act.colors.dim,
        )
        TerminalLink(
            if (expanded) "hide licences" else "show licences",
            onClick = { expanded = !expanded },
            modifier = Modifier.testTag(ABOUT_LICENCES_TOGGLE_TAG),
        )
        if (expanded) {
            Column(Modifier.testTag(ABOUT_LICENCES_TAG), verticalArrangement = Arrangement.spacedBy(2.dp)) {
                val shown = lines
                if (shown == null) {
                    Text("loading…", style = Act.type.meta, color = Act.colors.dim)
                } else if (shown.isEmpty()) {
                    Text("The licence list could not be loaded.", style = Act.type.meta, color = Act.colors.dim)
                } else {
                    shown.forEach { Text(it.text, style = Act.type.meta, color = Act.colors.ink) }
                }
            }
        }
    }
}
